//! Generates the Kotlin mirrors of ghostty's input types so the two sides
//! cannot drift: `zig-out/kotlin/<package path>/*.kt`.
const std = @import("std");
const vt = @import("ghostty-vt");

const package = "io.github.xchacha20_poly1305.libghostty";

pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 2) return error.Usage;
    var dir = try std.Io.Dir.cwd().createDirPathOpen(init.io, args[1], .{});
    defer dir.close(init.io);

    try writeFile(init.io, dir, "GhosttyKey.kt", writeKey);
    try writeFile(init.io, dir, "GhosttyMods.kt", writeMods);
}

fn writeFile(
    io: std.Io,
    dir: std.Io.Dir,
    name: []const u8,
    comptime body: fn (*std.Io.Writer) std.Io.Writer.Error!void,
) !void {
    var file = try dir.createFile(io, name, .{});
    defer file.close(io);
    var buf: [4096]u8 = undefined;
    var writer = file.writer(io, &buf);
    const w = &writer.interface;
    try w.print(
        \\// Generated by native/src/gen_kotlin.zig from libghostty-vt. Do not edit.
        \\package {s}
        \\
        \\
    , .{package});
    try body(w);
    try w.flush();
}

fn writeKey(w: *std.Io.Writer) !void {
    try w.writeAll(
        \\/** Physical keys, named after the W3C UI Events `code` values ghostty uses. */
        \\public enum class GhosttyKey(internal val value: Int) {
        \\
    );
    inline for (@typeInfo(vt.input.Key).@"enum".fields) |field| {
        try w.writeAll("    ");
        try writeUpperSnake(w, field.name);
        try w.print("({d}),\n", .{field.value});
    }
    try w.writeAll("}\n");
}

fn writeMods(w: *std.Io.Writer) !void {
    const Mods = vt.input.KeyMods;
    try w.writeAll(
        \\/** Modifier bits as ghostty's packed key modifiers; combine with `or`. */
        \\public object GhosttyMods {
        \\
    );
    inline for (.{ "shift", "ctrl", "alt", "super", "caps_lock", "num_lock" }) |name| {
        try writeBit(w, name, @bitOffsetOf(Mods, name));
    }
    // A side bit set means the right-hand key of that modifier is held.
    inline for (.{ "shift", "ctrl", "alt", "super" }) |name| {
        try writeBit(w, name ++ "_right", @bitOffsetOf(Mods, "sides") + @bitOffsetOf(Mods.Side, name));
    }
    try w.writeAll("}\n");
}

fn writeBit(w: *std.Io.Writer, comptime name: []const u8, comptime bit: comptime_int) !void {
    try w.writeAll("    public const val ");
    try writeUpperSnake(w, name);
    try w.print(": Int = 1 shl {d}\n", .{bit});
}

fn writeUpperSnake(w: *std.Io.Writer, name: []const u8) !void {
    for (name) |c| try w.writeByte(std.ascii.toUpper(c));
}
